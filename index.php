    <h2> Intro </h2>
    <p>I currently work at Facebook as a software engineer. Previously, I got my bachelors in computer science from the University of Washington. I entered college 3 years early through the <a href='https://robinsoncenter.uw.edu/programs/eep/' target='_blank'>early entrance program</a>.</p> <!--Before that, I got my GED through Robinson Center's <a href='https://robinsoncenter.uw.edu/programs/eep/' target='_blank'>transition school program</a>.</p>--> 
    <p>Within computer science my main interest is natural language processing, a subset of machine learning that focuses on language. My fascination with language originally stemmed from a book I read in Transition School English--Catherine Belsey's <em>Critical Practice</em>. To this date, I still think it's one of the most fascinating books I've read. It's a very dense English/linguistic philosophy book that goes into lengthy lectures about post-Sassurean philosophy (Barthes, Derrida, Foucault, etc.). I won't claim to have understood it 100%, but regardless, it led to my current adament belief that language is absolutely foundational to our society (a la Catherine Belsey, language defines our social ideologies, is defined /by/ our social ideologies, and the meaning derived from text is a reflection of the social structures at the time and place of its composition--even more than it is a reflection of writer or reader intent).</p>
    
    <p>Thus, I believe so-called "teaching machines to read and write" is probably one of the most intriguing, difficult, and potentially problematic (if we are not careful) challenges of the 21st century. I also believe will be <em>the</em> main driving force towards artificial general intelligence, if we will ever able to achieve that.</p>

    <p>But enough abstract futuristic talk, some specific areas and problems I'm interested in include: natural language understanding and generation, conversational AI, question-answering, fake news detection, social bias in machine learning, transfer learning, scaling large models, model interpretatibility, etc. It's a long list, but even this list is by no means exhaustive--just a taste of the interesting work I've been exposed to during my undergrad and time at Facebook.</p>

    <p>Anyways, there's still a lot for me to learn! I recently started an NLP blog <a href='blog/index.php'>here</a> to help myself as well as anyone else who's interested get a better grasp on the literature in the field. Feel free to check it out!</p>
